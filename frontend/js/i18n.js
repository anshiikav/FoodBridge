// Global translation lookup helper
window.t = function(key) {
  var lang = localStorage.getItem('foodbridge_lang') || 'en';
  if (lang === 'hi') {
    if (i18nDict[key]) return i18nDict[key];
    var norm = (key || '').replace(/\s+/g, ' ').trim();
    if (i18nDict[norm]) return i18nDict[norm];
  }
  return key;
};

function getLanguage() {
  return localStorage.getItem('foodbridge_lang') || 'en';
}

function setLanguage(lang) {
  localStorage.setItem('foodbridge_lang', lang);
  applyTranslations(lang);
}

function normalizeStr(str) {
  return (str || '').replace(/\s+/g, ' ').trim();
}

function applyTranslations(lang) {
  var isHindi = lang === 'hi';

  // 1. Process elements with explicit data-i18n attributes
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (!el.getAttribute('data-original-html')) {
      el.setAttribute('data-original-html', el.innerHTML);
    }
    if (isHindi && i18nDict[key]) {
      el.textContent = i18nDict[key];
    } else if (!isHindi && el.getAttribute('data-original-html')) {
      el.innerHTML = el.getAttribute('data-original-html');
    }
  });

  // 2. Comprehensive DOM text-node scanner
  // Covers all text containers without breaking child interactive structures
  var selectors = [
    'h1', 'h2', 'h3', 'h4', 'h5', 'h6',
    'p', 'a', 'button', 'label', 'th', 'td', 'li',
    '.stat-label', '.badge', '.sidebar-link', '.section-title', '.section-subtitle',
    '.btn', 'small', 'strong', 'option', '.safety-item span', '.faq-item span',
    '.metric-label', '.empty-state h3', '.empty-state p'
  ].join(', ');

  document.querySelectorAll(selectors).forEach(function(el) {
    // Skip inputs, scripts, SVGs, or language toggle itself
    if (el.id === 'langToggleBtn' || el.closest('#langToggleItem') || el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      return;
    }

    // Handle leaf elements or elements containing only text/simple formatting
    var hasComplexChildren = el.children.length > 0 && Array.from(el.children).some(function(c) {
      return c.tagName === 'DIV' || c.tagName === 'TABLE' || c.tagName === 'FORM' || c.tagName === 'UL';
    });
    if (hasComplexChildren) return;

    if (!el.getAttribute('data-en-text')) {
      el.setAttribute('data-en-text', el.textContent.trim());
    }

    var originalEn = el.getAttribute('data-en-text');
    var normEn = normalizeStr(originalEn);

    if (isHindi) {
      if (i18nDict[originalEn]) {
        el.textContent = i18nDict[originalEn];
      } else if (i18nDict[normEn]) {
        el.textContent = i18nDict[normEn];
      } else {
        // Match with emoji prefix preservation
        var emojiPrefixMatch = originalEn.match(/^([\uD800-\uDBFF\uDC00-\uDFFF\u2600-\u27BF\uFE00-\uFE0F\u200D\u2B50\u2705\u274C\s]+)/);
        if (emojiPrefixMatch) {
          var prefix = emojiPrefixMatch[1];
          var coreText = normalizeStr(originalEn.replace(prefix, ''));
          if (i18nDict[coreText]) {
            el.textContent = prefix + i18nDict[coreText];
          }
        }
      }
    } else {
      el.textContent = originalEn;
    }
  });

  // 3. Translate Form Placeholders
  document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach(function(input) {
    if (!input.getAttribute('data-en-placeholder')) {
      input.setAttribute('data-en-placeholder', input.getAttribute('placeholder'));
    }
    var origPlaceholder = input.getAttribute('data-en-placeholder');
    var normPl = normalizeStr(origPlaceholder);
    if (isHindi) {
      if (i18nDict[origPlaceholder]) input.setAttribute('placeholder', i18nDict[origPlaceholder]);
      else if (i18nDict[normPl]) input.setAttribute('placeholder', i18nDict[normPl]);
    } else {
      input.setAttribute('placeholder', origPlaceholder);
    }
  });

  // 4. Update Language Toggle Pill in Navbar
  var toggleBtn = document.getElementById('langToggleBtn');
  if (toggleBtn) {
    toggleBtn.innerHTML = isHindi
      ? '🌐 <strong>English</strong>'
      : '🌐 <strong>हिंदी (Hindi)</strong>';
    toggleBtn.title = isHindi ? 'Switch to English' : 'हिंदी में बदलें';
  }

  // 5. Notify active components
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

// Global hook so dynamically rendered cards/tables can re-apply translations
window.applyTranslations = applyTranslations;

document.addEventListener('DOMContentLoaded', function() {
  // Inject language toggle button into navigation bar or dashboard header
  var navLinks = document.querySelector('.nav-links');
  var headerActions = document.querySelector('.header-actions');

  if (navLinks && !document.getElementById('langToggleItem')) {
    var li = document.createElement('li');
    li.id = 'langToggleItem';
    li.style.display = 'flex';
    li.style.alignItems = 'center';
    li.style.margin = '0 6px';

    var currentLang = getLanguage();
    var isHindi = currentLang === 'hi';

    li.innerHTML = `
      <button type="button" id="langToggleBtn" class="btn btn-secondary btn-sm" style="padding: 5px 12px; font-size: 0.85rem; border-radius: 20px; border-color: var(--primary); color: var(--primary); font-weight: 600; cursor: pointer; background: #fff;">
        ${isHindi ? '🌐 <strong>English</strong>' : '🌐 <strong>हिंदी (Hindi)</strong>'}
      </button>
    `;

    navLinks.prepend(li);
  } else if (headerActions && !document.getElementById('langToggleBtn')) {
    var div = document.createElement('div');
    div.id = 'langToggleDiv';
    div.style.display = 'flex';
    div.style.alignItems = 'center';
    div.style.marginRight = '14px';

    var currentLang = getLanguage();
    var isHindi = currentLang === 'hi';

    div.innerHTML = `
      <button type="button" id="langToggleBtn" class="btn btn-secondary btn-sm" style="padding: 4px 12px; font-size: 0.85rem; border-radius: 20px; border: 1.5px solid var(--primary); color: var(--primary); font-weight: 600; cursor: pointer; background: #fff;">
        ${isHindi ? '🌐 <strong>English</strong>' : '🌐 <strong>हिंदी (Hindi)</strong>'}
      </button>
    `;

    headerActions.prepend(div);
  }

  document.getElementById('langToggleBtn')?.addEventListener('click', function(e) {
    e.preventDefault();
    var nextLang = getLanguage() === 'en' ? 'hi' : 'en';
    setLanguage(nextLang);
  });

  // Apply saved language preference on load
  if (getLanguage() === 'hi') {
    setTimeout(function() { applyTranslations('hi'); }, 60);
  }
});
